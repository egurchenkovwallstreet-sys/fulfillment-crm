"""Населённые пункты Москвы и МО (~50 км) для запросов WB shipping-points по city."""


def _dedupe_cities(cities: tuple[str, ...]) -> tuple[str, ...]:
  seen: set[str] = set()
  ordered: list[str] = []
  for city in cities:
    key = city.strip().lower().replace("ё", "е")
    if not key or key in seen:
      continue
    seen.add(key)
    ordered.append(city.strip())
  return tuple(ordered)


